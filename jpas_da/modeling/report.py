"""Collect sweep runs and baselines into one comparison table.

Reads ``reports/runs/<run>/metrics.json`` (VAE runs named
``<variant>-d<size>-r<rotation>``) and ``reports/runs/baselines.json``, and
writes ``reports/sweep_v2.md``. Every number is a mean over the rotations
present, with the spread (max - min) across rotations where it matters, so a
difference smaller than the rotation spread is not read as a result.

Columns:

* ``chi2/dof`` -- pooled test chi2/dof (``sum chi2 / sum dof``), the main
  reconstruction number; lower is better, but values below ~1 at large sizes
  mean the model is fitting noise (dof does not subtract parameters);
* ``median`` -- median per-object test chi2/dof;
* ``S/N <3`` / ``S/N >30`` -- pooled test chi2/dof in the faintest and brightest
  brightness bins;
* ``window/clean`` -- ratio of pooled chi2/dof of window-frame objects to clean
  ones (plan item: if window objects reconstruct clearly worse, move them to
  ``severe``);
* ``active`` -- active latent dimensions (VAE only), ``best ep`` -- selected
  epoch out of the run's epochs.
"""

from __future__ import annotations

from collections import defaultdict
import json
from pathlib import Path
import re
from typing import Annotated

from loguru import logger
import numpy as np
import typer

from jpas_da.config import REPORTS_DIR

app = typer.Typer()

RUNS_DIR = REPORTS_DIR / "runs"
REPORT_FILE = REPORTS_DIR / "sweep_v2.md"
RUN_NAME = re.compile(r"^(?P<variant>[a-z]+)-d(?P<dim>\d+)-r(?P<rot>\d+)$")


def _row(reconstruction: dict) -> dict[str, float]:
    by_snr, by_q = reconstruction["by_snr"], reconstruction["by_quality"]
    clean = by_q.get("clean", {}).get("chi2_dof_pooled", np.nan)
    window = by_q.get("window", {}).get("chi2_dof_pooled", np.nan)
    return {
        "chi2": reconstruction["overall"]["chi2_dof_pooled"],
        "median": reconstruction["overall"]["chi2_dof_median"],
        "faint": by_snr.get("0-3", {}).get("chi2_dof_pooled", np.nan),
        "bright": by_snr.get(">30", {}).get("chi2_dof_pooled", np.nan),
        "window_clean": window / clean,
    }


def collect(runs_dir: Path = RUNS_DIR) -> dict[tuple[str, int], list[dict[str, float]]]:
    """``(model, size) -> [one row per rotation]``."""
    groups: dict[tuple[str, int], list[dict[str, float]]] = defaultdict(list)
    for path in sorted(runs_dir.glob("*/metrics.json")):
        match = RUN_NAME.match(path.parent.name)
        if not match:
            continue
        metrics = json.loads(path.read_text())
        row = _row(metrics["test"]["reconstruction"])
        row["active"] = metrics["test"]["latent"]["active_dims"]
        row["best_epoch"] = metrics["best_epoch"]
        row["epochs"] = metrics["config"]["train"]["epochs"]
        row["rotation"] = int(match["rot"])
        groups[(f"vae-{match['variant']}", int(match["dim"]))].append(row)
    baselines = runs_dir / "baselines.json"
    if baselines.exists():
        for run in json.loads(baselines.read_text())["runs"]:
            row = _row(run["test"]["reconstruction"])
            row["rotation"] = run["rotation"]
            groups[(run["method"], run["latent_dim"])].append(row)
    return groups


def _fmt(values: list[float], spread: bool = False) -> str:
    values = [v for v in values if np.isfinite(v)]
    if not values:
        return "–"
    text = f"{np.mean(values):.3f}"
    if spread and len(values) > 1:
        text += f" ±{(max(values) - min(values)) / 2:.3f}"
    return text


def render(groups: dict[tuple[str, int], list[dict[str, float]]]) -> str:
    lines = [
        "# Sweep v2: test-tile reconstruction",
        "",
        "Generated by `python -m jpas_da.modeling.report` from `reports/runs/`. Means over",
        "rotations (n = number of rotations); ± is half the range across rotations.",
        "All models are scored with the same chi2 and the VAE's noise model",
        "(eps = 0.1, common-mode term on). See the module docstring for the columns.",
        "",
        "| model | d | n | chi2/dof | median | S/N <3 | S/N >30 | window/clean | active | best ep |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for (model, dim), rows in sorted(groups.items(), key=lambda item: (item[0][1], item[0][0])):

        def col(key: str, rows=rows) -> list[float]:
            return [r[key] for r in rows]

        active = f"{np.mean(col('active')):.1f}/{dim}" if "active" in rows[0] else "–"
        best = (
            f"{np.mean(col('best_epoch')):.0f}/{rows[0]['epochs']}"
            if "best_epoch" in rows[0]
            else "–"
        )
        lines.append(
            f"| {model} | {dim} | {len(rows)} | {_fmt(col('chi2'), True)} | {_fmt(col('median'))} | "
            f"{_fmt(col('faint'))} | {_fmt(col('bright'))} | {_fmt(col('window_clean'))} | "
            f"{active} | {best} |"
        )
    return "\n".join(lines) + "\n"


@app.command()
def main(
    runs_dir: Annotated[Path, typer.Option("--runs")] = RUNS_DIR,
    output_path: Annotated[Path, typer.Option("--output")] = REPORT_FILE,
) -> str:
    text = render(collect(runs_dir))
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(text)
    logger.success(f"Wrote {output_path}")
    print(text)
    return text


if __name__ == "__main__":
    app()
